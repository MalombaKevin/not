// step must not share a factor with the list length, so every entry is used before any repeats
export const MODES = {
  motivation: { items: QUOTES, step: 37, credit: a => a },
  verse: { items: VERSES, step: 41, credit: a => `${a} (KJV)` }
};

export const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
export const WEEKDAYS = ["Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday"];
export const DAY_MS = 86400000;

export function parseDate(param) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(param || "");
  if (!m) return new Date();
  const [, y, mo, d] = m.map(Number);
  return new Date(y, mo - 1, d);
}

export function entryFor(date, modeName) {
  const { items, step } = MODES[modeName];
  const dayNumber = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / DAY_MS);
  const i = (((dayNumber * step) % items.length) + items.length) % items.length;
  return items[i];
}

export function longDate(date) {
  return `${WEEKDAYS[date.getDay()]}, ${date.getDate()} ${MONTHS[date.getMonth()]} ${date.getFullYear()}`;
}
